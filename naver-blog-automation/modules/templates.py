def get_system_prompt(category: str, post_type: str) -> str:
    """카테고리 + 글 유형 조합에 맞는 시스템 프롬프트 반환"""
    base = TEMPLATE_MAP.get(f"{category}_{post_type}") or TEMPLATE_MAP.get(f"default_{post_type}")
    return base + "\n\n" + COMMON_PRINCIPLES


def get_user_prompt(
    category: str,
    post_type: str,
    keyword: str,
    sub_keywords: list,
    product_info: dict,
    brand_connect_url: str,
) -> str:
    """실제 글 생성 요청 프롬프트"""
    specs_text = ""
    if product_info.get("specs"):
        specs_lines = [f"  - {k}: {v}" for k, v in list(product_info["specs"].items())[:10]]
        specs_text = "\n".join(specs_lines)

    sub_kw_text = ", ".join(sub_keywords) if sub_keywords else "없음"
    price_text = f"{product_info.get('price', '')}원" if product_info.get("price") else "가격 미확인"

    return f"""
[작성 요청 정보]
- 메인 키워드: {keyword}
- 카테고리: {CATEGORIES.get(category, category)}
- 글 유형: {POST_TYPES.get(post_type, post_type)}
- 반드시 포함할 서브키워드: {sub_kw_text}

[제품 정보]
- 제품명: {product_info.get('name', '제품명 미확인')}
- 가격: {price_text}
- 평점: {product_info.get('rating', '미확인')}
- 리뷰수: {product_info.get('review_count', '미확인')}
- 제품 설명: {product_info.get('description', '제품 설명 없음')}
- 스펙:
{specs_text if specs_text else '  - 스펙 정보 없음 (알고 있는 정보로 작성)'}

[구매 링크 (Brand Connect)]
{brand_connect_url}

[이미지 안내]
글의 적절한 위치에 [이미지1], [이미지2], [이미지3] 등으로 표시해주세요.
(총 3~5개 이미지 삽입 위치 표시)

위 정보를 바탕으로 실제 블로거가 쓴 것처럼 자연스럽고 유익한 블로그 글을 작성해주세요.
제목도 함께 작성해주세요.
"""


